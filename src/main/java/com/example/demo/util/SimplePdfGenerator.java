package com.example.demo.util;

import com.example.demo.model.VendorInvoice;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Generates a lightweight, valid PDF 1.4 invoice document without external dependencies.
 */
public final class SimplePdfGenerator {

    private SimplePdfGenerator() {
    }

    public static byte[] generateInvoicePdf(VendorInvoice inv) {
        List<String> lines = List.of(
                "ENTERTAINMENT WORLD - TAX INVOICE",
                "------------------------------------------------------------",
                "Invoice Number   : " + safe(inv.getInvoiceNumber()),
                "Booking Ref      : " + safe(inv.getBooking().getBookingCode()),
                "Invoice Date     : " + safe(String.valueOf(inv.getInvoiceDate())),
                "Due Date         : " + safe(String.valueOf(inv.getDueDate())),
                "Payment Status   : " + safe(inv.getPaymentStatus().name()),
                "------------------------------------------------------------",
                "Vendor Company   : " + safe(inv.getVendorCompanyName()),
                "Vendor Email     : " + safe(inv.getVendorEmail()),
                "Customer Org     : " + safe(inv.getCustomerOrganization()),
                "Customer Contact : " + safe(inv.getCustomerContact()) + " (" + safe(inv.getCustomerEmail()) + ")",
                "------------------------------------------------------------",
                "Service          : " + safe(inv.getServiceDescription()),
                "Quantity         : " + inv.getQuantity(),
                "Unit Price       : INR " + inv.getUnitPrice(),
                "Subtotal         : INR " + inv.getSubtotal(),
                "Tax (18% GST)    : INR " + inv.getTaxAmount(),
                "Total Amount     : INR " + inv.getTotalAmount(),
                "Paid Amount      : INR " + inv.getPaidAmount(),
                "------------------------------------------------------------",
                "Generated by Entertainment World Vendor Management Portal"
        );
        return buildSimplePdf(null, lines);
    }

    public static byte[] buildSimplePdf(String title, List<String> bodyLines) {
        List<String> lines = new ArrayList<>();
        if (title != null && !title.isBlank()) {
            lines.add(safe(title));
            lines.add("------------------------------------------------------------");
        }
        if (bodyLines != null) {
            bodyLines.forEach(l -> lines.add(safe(l)));
        }

        StringBuilder stream = new StringBuilder();
        stream.append("BT\n/F1 11 Tf\n50 760 Td\n16 TL\n");
        for (int i = 0; i < lines.size(); i++) {
            String escaped = escapePdfText(lines.get(i));
            if (i == 0) {
                stream.append("(").append(escaped).append(") Tj\n");
            } else {
                stream.append("T* (").append(escaped).append(") Tj\n");
            }
        }
        stream.append("ET\n");
        byte[] contentBytes = stream.toString().getBytes(StandardCharsets.US_ASCII);

        ByteArrayOutputStream out = new ByteArrayOutputStream();
        List<Integer> offsets = new ArrayList<>();
        writeAscii(out, "%PDF-1.4\n");

        offsets.add(out.size());
        writeAscii(out, "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");

        offsets.add(out.size());
        writeAscii(out, "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n");

        offsets.add(out.size());
        writeAscii(out, "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj\n");

        offsets.add(out.size());
        writeAscii(out, "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n");

        offsets.add(out.size());
        writeAscii(out, "5 0 obj\n<< /Length " + contentBytes.length + " >>\nstream\n");
        out.writeBytes(contentBytes);
        writeAscii(out, "endstream\nendobj\n");

        int xrefPos = out.size();
        writeAscii(out, "xref\n0 " + (offsets.size() + 1) + "\n0000000000 65535 f \n");
        for (int offset : offsets) {
            writeAscii(out, String.format("%010d 00000 n \n", offset));
        }
        writeAscii(out, "trailer\n<< /Size " + (offsets.size() + 1) + " /Root 1 0 R >>\nstartxref\n" + xrefPos + "\n%%EOF\n");
        return out.toByteArray();
    }

    private static void writeAscii(ByteArrayOutputStream out, String text) {
        out.writeBytes(text.getBytes(StandardCharsets.US_ASCII));
    }

    private static String safe(String value) {
        return value == null ? "" : value.replaceAll("[^\\x20-\\x7E]", " ");
    }

    private static String escapePdfText(String text) {
        return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)");
    }
}
